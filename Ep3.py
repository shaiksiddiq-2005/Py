# COMPARSION OPERATOR (    <, >, <=, >=, ==, !=   )
print(2<5) # True
print(2>5) #False
print(2<=5) #true
print(2>=5) #False
print(2==5) #False
print(2!=5) #true







# LOGICAL OPERATOR (   or, and, not  )
statement1 = 2< 5; # True
statement2 = 5> 10; # false
statement3 = (2==2)

print(statement1 or statement2); # true
print(statement1 and statement2); # false

print(statement3); #true
print(not statement3); # ( not true ) ====> false  


