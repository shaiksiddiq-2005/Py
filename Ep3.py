#OPERATORS


# Arithmetic operators (+ ,- , /, %, *)
print(4+2); 
print(4-2);
print(4*2);
print(4/2); # It gives the output in Float
print(4//2); # It gives the output in Integer
print(4**2); # Power ======> 16
print(4%2); # reminder =====> 0






#Assignment Operator
